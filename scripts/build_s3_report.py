#!/usr/bin/env python3
"""Write docs/s3-findings.md from the S3 JSON receipts (no hand-typed numbers)."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
S3 = ROOT / 'evidence/s3'


def j(p):
    return json.loads((ROOT / p).read_text())


def f4(x):
    return f'{x:.4f}'


def ci(d):
    return f"[{d['ci95'][0]:.4f}, {d['ci95'][1]:.4f}]"


def arm_table(scores, labels):
    out = ['| Arm | DTI | 95 % CI |', '|---|---:|---|']
    for k, lab in labels:
        if k in scores:
            out.append(f'| {lab} | {f4(scores[k]["dti"])} | {ci(scores[k])} |')
    return '\n'.join(out)


def main():
    e1 = j('evidence/s3/run_card.json')
    e2 = j('evidence/s3/e2/run_card.json')
    cal = j('evidence/s3/proxy_calibration.json')
    can = j('evidence/s3/canaries.json')
    b1 = j('evidence/s3/instrumentB_prime.json')
    b2 = j('evidence/s3/e2/instrumentB_prime.json')
    a1 = j('evidence/s3/instrumentA_holdout.json')
    d1 = b1['paired_differences']['h33_reference']
    d2h = b2['paired_differences']['h33_reference']
    d2r = b2['paired_differences']['random_stratified']
    top = sorted(can['features'].items(), key=lambda kv: -kv[1]['strength'])[:5]
    cal_rows = ['| Reported live score | B′ DTI | A DTI | Dots | File | Score source |', '|---:|---:|---:|---:|---|---|']
    for r in sorted([r for r in cal['rows'] if 'error' not in r], key=lambda r: -r['live_score_reported']):
        cal_rows.append(f"| {r['live_score_reported']:.4f} | {r['b_prime_dti']:.4f} | {r['a_dti']:.4f} | "
                        f"{r['positive_pixels']:,} | `{r['file']}` | {r['score_source']} |")
    m1 = e2['marginals']
    tm = j('evidence/s3/terrain_marginals.json')
    terrain_line = '; '.join(f"{r['label']} {r['frac_steep_top_quartile']:.3f}" for r in tm['rows'])
    text = f"""# Session 3 findings — supervised proxy ranking, calibration, and the submission decision

Generated by `scripts/build_s3_report.py` from `evidence/s3/**`. Evidence classes: **PROXY-DTI**
(B′, SGMC-only faults ≥ 3 px off the catalogue, leave-one-quadrant-out), **HOLDOUT-DTI** (A, shared
hide-and-recover, evaluator `{b1['evaluator_version']}`), and **owner/user-reported live scores**
(never organizer-confirmed here). No weekly slot was used.

## Bottom line

* **Download:** both new files are unique against the 62 archived registry rasters and pass the
  shared validator (finite, values in {{0, 1}}, EPSG:32611, 3730 × 3292, 100 m transform).
* **Submit a weekly slot: not recommended for either.** E1 passed its pre-registered proxy gate
  but is vetoed because the proxy demonstrably does not track the live board, and E1's gain is
  confounded with steep terrain. E2, which removes that confound, is negative.

## E1 — proxy-trained ranking with H33 spacing (`docs/preregistration-s3.md`)

LOQO out-of-fold AUC per quadrant: {', '.join(f'{x:.3f}' for x in e1['loqo_oof_auc']['candidate'])}.
Leakage canary: no alarm; strongest single features (AUC vs B′ label, 1,000,000-pixel sample):
{', '.join(f"`{k}` {v['auc']:.3f}" for k, v in top)}.

{arm_table(b1['scores'], [('candidate', 'E1 candidate'), ('abl_physics_only', 'ablation: physics only'),
                          ('abl_geometry_only', 'ablation: catalogue geometry only'),
                          ('abl_stratified7_placement', 'ablation: 7×7 stratified placement'),
                          ('h33_reference', 'H33 (archived, user-reported 0.2778 live)'),
                          ('p4_published', 'P4 (session 2 file)'), ('random_control', 'random')])}

Paired B′ Δ (E1 − H33) = {d1['delta']:+.4f}, 95 % CI [{d1['ci95'][0]:+.4f}, {d1['ci95'][1]:+.4f}]
({b1['scores']['candidate']['withheld_positive_pixels']:,} proxy positives). Instrument A: E1
{f4(a1['scores']['candidate']['dti'])} vs H33 {f4(a1['scores']['h33_reference']['dti'])} vs random
{f4(a1['scores']['random_control']['dti'])}. Pre-registered rule outcome: **{e1['preregistered_rule_verdict']}**.
Final verdict after the conservative veto: **{e1['verdict']}**.

## Calibration diagnostic — do the offline instruments track the live board?

Spearman(live, B′) = **{cal['spearman_live_vs_b_prime']:.3f}**; Spearman(live, A) =
**{cal['spearman_live_vs_a']:.3f}** (n = {cal['n']}). Neither instrument orders archived files the way
the live board did. Among files of comparable size (≈ 37–44 k dots) B′ is nearly flat, and the one
with the highest B′ (GEMSDOE49 gate_ortho) was reported lower live than H33.

{chr(10).join(cal_rows)}

## E2 — ranking only within H33's distance × slope strata (`docs/preregistration-s3-e2.md`)

Steep-quartile fraction (domain quartile used by the strata): E2 production
{m1['production']['steep_top_quartile']:.3f}, H33 {m1['h33_reference']['steep_top_quartile']:.3f}.
With the footprint quartile (`evidence/s3/terrain_marginals.json`): {terrain_line}.

{arm_table(b2['scores'], [('candidate', 'E2 candidate'), ('random_stratified', 'random within the same strata'),
                          ('h33_reference', 'H33'), ('random_control', 'random')])}

Paired B′ Δ (E2 − H33) = {d2h['delta']:+.4f} [{d2h['ci95'][0]:+.4f}, {d2h['ci95'][1]:+.4f}];
Δ (E2 − random-stratified) = {d2r['delta']:+.4f} [{d2r['ci95'][0]:+.4f}, {d2r['ci95'][1]:+.4f}].
Both lower bounds are below zero → **{e2['verdict']}**. Once terrain and distance are matched, the
model adds no significant within-stratum information on this proxy.

Annotations recorded in the E2 card: {e2['annotation_s3_e1_arm']} {e2['annotation_h33_domain']}

## Why H33 scored 0.2778 — what this session adds

The calibration table is the only live-linked evidence available. Among the ≈ 37–44 k-dot files,
reported live score rose as dots nearest the catalogue were deleted (D28 → H27 → H33), and fell for
the one file that concentrated dots in steep terrain (gate_ortho). H33 is therefore best explained as
a well-spaced, terrain-neutral sample of the 0.3–8 km band around mapped faults. Beating it needs
information that the live board rewards; our two proxies cannot currently measure that, which is the
main blocker named in `docs/irregularities.md`.

## Files

| File | SHA-256 | Download | Submit |
|---|---|---|---|
| `{Path(e1['artifact']).name}` | `{e1['raster_sha256']}` | yes | **no** (vetoed) |
| `{Path(e2['artifact']).name}` | `{e2['raster_sha256']}` | yes | **no** (negative) |
"""
    (ROOT / 'docs/s3-findings.md').write_text(text)
    print('wrote docs/s3-findings.md')


if __name__ == '__main__':
    main()
